package com.alibaba.nacos.ai.service.ard;

import com.alibaba.nacos.ai.model.ard.ArdChunk;
import com.alibaba.nacos.ai.model.ard.ArdEntry;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.jdbc.core.JdbcTemplate;

import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;

/**
 * Tests for {@link JdbcArdIndexRepository}.
 *
 * @author nacos
 */
class JdbcArdIndexRepositoryTest {
    
    private JdbcTemplate jdbcTemplate;
    
    private JdbcArdIndexRepository repository;
    
    @BeforeEach
    void setUp() {
        JdbcDataSource dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:ard_index_repository;DB_CLOSE_DELAY=-1");
        jdbcTemplate = new JdbcTemplate(dataSource);
        jdbcTemplate.execute("DROP TABLE IF EXISTS ai_resource_ard_chunk");
        jdbcTemplate.execute("DROP TABLE IF EXISTS ai_resource_ard_entry");
        jdbcTemplate.execute("CREATE TABLE ai_resource_ard_entry ("
            + "id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
            + "namespace_id varchar(128) NOT NULL, resource_type varchar(32) NOT NULL,"
            + "resource_name varchar(256) NOT NULL, resource_version varchar(64) NOT NULL,"
            + "display_name varchar(256) NOT NULL, c_desc varchar(2048), tags clob,"
            + "capabilities clob, representative_queries clob, metadata clob,"
            + "source_digest varchar(64) NOT NULL, status varchar(32) NOT NULL,"
            + "generate_mode varchar(32) NOT NULL, gmt_create timestamp NOT NULL,"
            + "gmt_modified timestamp NOT NULL,"
            + "UNIQUE(namespace_id, resource_type, resource_name, resource_version))");
        jdbcTemplate.execute("CREATE TABLE ai_resource_ard_chunk ("
            + "id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, entry_id bigint NOT NULL,"
            + "namespace_id varchar(128) NOT NULL, resource_type varchar(32) NOT NULL,"
            + "resource_name varchar(256) NOT NULL, resource_version varchar(64) NOT NULL,"
            + "chunk_type varchar(64) NOT NULL, chunk_text varchar(4096) NOT NULL,"
            + "canonical_text varchar(4096) NOT NULL, language varchar(16),"
            + "chunk_hash varchar(64) NOT NULL, metadata clob, status varchar(32) NOT NULL,"
            + "gmt_create timestamp NOT NULL, gmt_modified timestamp NOT NULL)");
        repository = new JdbcArdIndexRepository(jdbcTemplate);
    }
    
    @Test
    void replaceEntryShouldRollbackDeleteAndPartialInsert() {
        jdbcTemplate.update("INSERT INTO ai_resource_ard_entry "
            + "(namespace_id, resource_type, resource_name, resource_version, display_name, "
            + "source_digest, status, generate_mode, gmt_create, gmt_modified) "
            + "VALUES (?, ?, ?, ?, ?, ?, ?, ?, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP)",
            "public", "skill", "avatar", "1.0.0", "old", "old-digest", "enabled", "auto");
        Long oldEntryId = jdbcTemplate.queryForObject(
            "SELECT id FROM ai_resource_ard_entry WHERE display_name='old'", Long.class);
        jdbcTemplate.update("INSERT INTO ai_resource_ard_chunk "
            + "(entry_id, namespace_id, resource_type, resource_name, resource_version, "
            + "chunk_type, chunk_text, canonical_text, chunk_hash, status, "
            + "gmt_create, gmt_modified) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, "
            + "CURRENT_TIMESTAMP, CURRENT_TIMESTAMP)",
            oldEntryId, "public", "skill", "avatar", "1.0.0", "description", "old", "old",
            "old-hash", "enabled");
        
        ArdEntry replacement = entry("new");
        ArdChunk validChunk = chunk("valid", "valid");
        ArdChunk invalidChunk = chunk("invalid", null);
        
        assertThrows(DataIntegrityViolationException.class,
            () -> repository.replaceEntry(replacement, List.of(validChunk, invalidChunk)));
        
        assertEquals("old", jdbcTemplate.queryForObject(
            "SELECT display_name FROM ai_resource_ard_entry", String.class));
        assertEquals(1, jdbcTemplate.queryForObject(
            "SELECT COUNT(1) FROM ai_resource_ard_chunk", Integer.class));
    }
    
    private ArdEntry entry(String displayName) {
        ArdEntry entry = new ArdEntry();
        entry.setNamespaceId("public");
        entry.setResourceType("skill");
        entry.setResourceName("avatar");
        entry.setResourceVersion("1.0.0");
        entry.setDisplayName(displayName);
        entry.setSourceDigest("new-digest");
        entry.setStatus(ArdIndexConstants.STATUS_ENABLED);
        entry.setGenerateMode(ArdIndexConstants.GENERATE_MODE_AUTO);
        return entry;
    }
    
    private ArdChunk chunk(String text, String canonicalText) {
        ArdChunk chunk = new ArdChunk();
        chunk.setChunkType(ArdIndexConstants.CHUNK_TYPE_DESCRIPTION);
        chunk.setChunkText(text);
        chunk.setCanonicalText(canonicalText);
        chunk.setChunkHash(text + "-hash");
        chunk.setStatus(ArdIndexConstants.STATUS_ENABLED);
        return chunk;
    }
}
